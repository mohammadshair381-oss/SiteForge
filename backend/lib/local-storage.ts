import { readFile, writeFile, unlink, stat } from "node:fs/promises";
import { join, basename, extname } from "node:path";
import { HttpError } from "./api";

// Local media directory: outside public/, git-ignored
const LOCAL_MEDIA_ROOT = join(process.cwd(), "media-dev");

// Ensure directory exists on module load
try {
  require("node:fs").mkdirSync(LOCAL_MEDIA_ROOT, { recursive: true });
} catch {}

/**
 * Normalises a storage key and rejects path traversal.
 * Storage key format: media/{businessId}/{uuid}{ext}
 */
function normalizeKey(key: string): string {
  if (key.includes("..") || key.startsWith("/") || key.startsWith("\\")) {
    throw new HttpError(400, "Invalid storage key", "invalid_key");
  }
  return key;
}

/**
 * Upload a file to local storage.
 * Key is generated by buildStorageKey() and is guaranteed safe.
 */
export async function localUpload(key: string, body: Buffer, contentType: string): Promise<void> {
  const safeKey = normalizeKey(key);
  const filePath = join(LOCAL_MEDIA_ROOT, safeKey);
  await writeFile(filePath, body);
}

/**
 * Remove a file from local storage.
 * Idempotent: does not throw if file does not exist.
 */
export async function localRemove(key: string): Promise<void> {
  const safeKey = normalizeKey(key);
  const filePath = join(LOCAL_MEDIA_ROOT, safeKey);
  try {
    await unlink(filePath);
  } catch {}
}

/**
 * Check if a file exists in local storage.
 */
export async function localExists(key: string): Promise<boolean> {
  const safeKey = normalizeKey(key);
  const filePath = join(LOCAL_MEDIA_ROOT, safeKey);
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

/**
 * Detect MIME type from file magic bytes.
 */
export function detectMimeFromBytes(buf: Buffer): string | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "image/jpeg";
  if (
    buf.length >= 8 &&
    buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47 && buf[4] === 0x0d && buf[5] === 0x0a && buf[6] === 0x1a && buf[7] === 0x0a
  )
    return "image/png";
  if (buf.length >= 6) {
    const ascii = buf.subarray(0, 6).toString("ascii");
    if (ascii === "GIF87a" || ascii === "GIF89a") return "image/gif";
  }
  if (
    buf.length >= 12 &&
    buf[0] === 0x52 && buf[1] === 0x49 && buf[2] === 0x46 && buf[3] === 0x46 && buf.subarray(8, 12).toString("ascii") === "WEBP"
  )
    return "image/webp";
  return null;
}

/** Extension from the last path segment of the key. */
function keyToExtension(key: string): string {
  const parts = key.split("/");
  if (parts.length < 3) return ".bin";
  const fileName = parts[parts.length - 1];
  const ext = require("path").extname(fileName);
  return ext || ".bin";
}

/** Content-Type from extension. */
export function getContentType(key: string): string {
  const ext = keyToExtension(key).toLowerCase();
  const mimeMap: Record<string, string> = {
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".gif": "image/gif",
    ".webp": "image/webp",
  };
  return mimeMap[ext] || "application/octet-stream";
}

/** Build a local public URL for a media key, pointing to the serving route.
 *  The key is base64-encoded in the URL query parameter for safe transmission. */
export function localMediaUrl(key: string, businessId: string): string {
  const encodedKey = Buffer.from(key).toString("base64");
  return `/api/businesses/${businessId}/local-media?key=${encodedKey}`;
}

/** Extract businessId from a storage key of format media/{businessId}/{uuid}{ext}. */
function businessIdFromKey(key: string): string | null {
  const parts = key.split("/");
  if (parts.length < 3) return null;
  return parts[1].toLowerCase();
}

/** Get content type from key, using extension-based lookup. */
export function getContentTypeFromKey(key: string): string {
  return getContentType(key);
}